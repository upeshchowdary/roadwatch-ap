"""Generate a Teammate Run Card (runs/cards/<run_id>.md) + importable notebook for a Kaggle run.

Usage: uv run python scripts/make_run_card.py baseline_a full_s1 --person A --hours 3
Writes:
  kaggle/cards/<model>_<run>.ipynb   (config already injected; no secrets inside)
  runs/cards/<run_id>.md             (click-by-click steps for a non-coder)
and appends a 'card_issued' row to runs/RUN_LOG.csv.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from kaggle_push import build  # noqa: E402

REPO = "https://github.com/upeshchowdary/roadwatch-ap"

CARD = """# Teammate Run Card — {run_id}

| | |
|---|---|
| Person | **{person}** ({role}) |
| Model / run | {model} / {run} (seed {seed}) |
| Config hash | `{config_hash}` |
| GPU time | about **{hours} h** of your weekly 6 h Kaggle GPU quota (hard stop built in) |
| Your time | ~10 min to start + ~5 min to download at the end. Laptop can be OFF while it runs. |

## A. Start the run (~10 min)

1. Download the notebook file: open
   {repo}/blob/main/kaggle/cards/{nb_name}
   → click the **Download raw file** button (down-arrow icon, top-right of the file view).
2. Open https://www.kaggle.com/code → click **+ New Notebook** (top-left).
3. In the notebook editor: menu **File → Import Notebook** → **Browse Files** → pick
   `{nb_name}` → **Import**. (If asked "replace current notebook?" → yes.)
4. Right sidebar → **Input** section → **+ Add Input** → search `deepglobe road extraction`
   → pick **DeepGlobe Road Extraction Dataset** by *balraj98* → click the **+** → close.
5. Right sidebar → **Session options**:
   - **Accelerator** → **GPU T4 x2**
   - **Internet** → **On** (needs a phone-verified account)
6. Rename the notebook (top-left title) to: `{slug}`
7. Top-right **Save Version** → choose **Save & Run All (Commit)** → **Save**.
8. You should see "Version 1 · Running". You can close the browser and switch off the laptop.

## B. When it finishes (~{hours} h later)

1. Open https://www.kaggle.com/code → **Your Work** → `{slug}` → status **Succeeded**.
2. Click the **Output** tab → **Download All** (a zip).
3. Send the zip (Google Drive link) to the project lead, or upload it: open
   https://huggingface.co/organizations/{hf_org} → **New → Dataset** is NOT needed — just send the
   Drive link; the lead uploads checkpoints to Hugging Face.
4. Reply in the group: `done {run_id}` + the **val IoU** printed at the end of the log
   (Logs tab → last lines contain `TEST:` and `best_val_iou`).

## If stuck
- "GPU quota exceeded" → you have used your 6 h this week; tell the lead (quota resets Saturday).
- "Internet must be verified" → Kaggle **Settings → Phone Verification** first.
- Red error in the log → screenshot the last 20 lines of the **Logs** tab and send it.
"""

ROLES = {"A": "Spatial evidence & provenance lead", "B": "GIS workflow & delivery lead",
         "C": "Validation & uncertainty lead", "D": "Training-runs & reproducibility lead",
         "lead": "Model engineering lead"}


def notebook(code: str) -> dict:
    return {
        "nbformat": 4, "nbformat_minor": 5,
        "metadata": {"kernelspec": {"name": "python3", "display_name": "Python 3", "language": "python"},
                     "language_info": {"name": "python"}},
        "cells": [
            {"cell_type": "markdown", "id": "intro", "metadata": {},
             "source": ["# RoadWatch AP training run\n",
                        "Generated by scripts/make_run_card.py — do not edit. Run with **Save & Run All**."]},
            {"cell_type": "code", "id": "train", "metadata": {}, "execution_count": None,
             "outputs": [], "source": code.splitlines(keepends=True)},
        ],
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("model")
    ap.add_argument("run")
    ap.add_argument("--person", required=True)
    ap.add_argument("--hours", type=float, default=3.0)
    ap.add_argument("--hf-org", default="roadwatch-ap")
    a = ap.parse_args()

    out, cfg, meta = build(a.model, a.run)
    code = (out / "train.py").read_text(encoding="utf-8")
    nb_name = f"{a.model}_{a.run}.ipynb"
    nb_path = ROOT / "kaggle" / "cards" / nb_name
    nb_path.parent.mkdir(parents=True, exist_ok=True)
    nb_path.write_text(json.dumps(notebook(code), indent=1), encoding="utf-8")

    card = CARD.format(run_id=cfg["run_id"], person=a.person, role=ROLES.get(a.person, "teammate"),
                       model=a.model, run=a.run, seed=cfg["seed"], config_hash=cfg["config_hash"],
                       hours=a.hours, repo=REPO, nb_name=nb_name, slug=meta["title"], hf_org=a.hf_org)
    card_path = ROOT / "runs" / "cards" / f"{cfg['run_id']}.md"
    card_path.write_text(card, encoding="utf-8")
    with (ROOT / "runs" / "RUN_LOG.csv").open("a", newline="", encoding="utf-8") as f:
        csv.writer(f).writerow([cfg["run_id"], a.person, "", meta["title"], cfg["config_hash"],
                                datetime.now(UTC).isoformat(timespec="seconds"), "", "", "card_issued", ""])
    print(f"card: {card_path.relative_to(ROOT)}\nnotebook: {nb_path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
